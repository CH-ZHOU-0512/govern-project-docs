import {
  existsSync,
  readFileSync,
  watch,
} from "node:fs";
import { basename, dirname, join, relative, resolve } from "node:path";
import console from "node:console";
import process from "node:process";
import { clearTimeout, setTimeout } from "node:timers";
import { fileURLToPath } from "node:url";
import {
  collectMarkdownFiles,
  compareText,
  countLines,
  encodeMarkdownPath,
  loadGovernanceConfig,
  normalizePath,
  parseCliArguments,
  parseFrontMatter,
  repositoryPath as relativeRepositoryPath,
  writeFileAtomic,
} from "./docs-toolkit.mjs";

const usage =
  "Usage: node scripts/document-index.mjs [generate|check|query <term>|watch] [--repo <path>] [--config <path>]";

let cli;
try {
  cli = parseCliArguments(process.argv.slice(2), {
    booleanFlags: ["--help"],
    valueFlags: ["--config", "--repo"],
  });
} catch (error) {
  console.error(error.message);
  console.error(usage);
  process.exit(2);
}
if (cli.options["--help"]) {
  console.log(usage);
  process.exit(0);
}

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(
  cli.options["--repo"] ?? resolve(scriptDirectory, ".."),
);
const configPath = resolve(
  cli.options["--config"] ??
    join(repositoryRoot, "scripts", "docs-governance.config.json"),
);
if (!existsSync(configPath)) {
  console.error(`Missing documentation governance config: ${configPath}`);
  process.exit(2);
}
let config;
try {
  config = loadGovernanceConfig(configPath, repositoryRoot);
} catch (error) {
  console.error(error.message);
  process.exit(2);
}
const docsRoot = join(repositoryRoot, config.docsRoot);
const generatedRoot = join(repositoryRoot, config.generatedRoot);
const markdownOutputPath = join(generatedRoot, "document-index.md");
const jsonOutputPath = join(generatedRoot, "document-index.json");
const generatedHeader =
  "<!-- GENERATED by scripts/document-index.mjs. DO NOT EDIT. -->";
const escapedPrefixes = config.stableIdPrefixes.map((prefix) =>
  prefix.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"),
);
const stableIdentifierPattern = new RegExp(
  `\\b(?:${escapedPrefixes.join("|")})-[A-Z0-9-]+\\b`,
  "g",
);
const stableIdentifierExactPattern = new RegExp(
  `^(?:${escapedPrefixes.join("|")})-[A-Z0-9-]+$`,
  "i",
);
const routingPaths = new Set(config.routingPaths);
const routingPatterns = config.routingPatterns.map((pattern) => new RegExp(pattern));

function repositoryPath(path) {
  return relativeRepositoryPath(repositoryRoot, path);
}

function categoryFor(absolutePath) {
  const segments = normalizePath(relative(docsRoot, absolutePath)).split("/");
  return segments.length === 1 ? "index" : segments[0];
}

function accessFor(path) {
  if (
    routingPaths.has(path) ||
    routingPatterns.some((pattern) => pattern.test(path))
  ) {
    return "routing";
  }
  if (path.startsWith(`${config.docsRoot}/archive/`)) return "historical";
  if (
    path.startsWith(`${config.docsRoot}/source/`) ||
    path.startsWith(`${config.docsRoot}/reference/`)
  ) {
    return "source";
  }
  if (path.startsWith(`${config.generatedRoot}/`)) return "derived";
  return "on-demand";
}

function parseDocument(absolutePath) {
  const path = repositoryPath(absolutePath);
  const content = readFileSync(absolutePath, "utf8");
  const lines = content.split(/\r?\n/);
  const metadata = parseFrontMatter(content) ?? {};
  const headings = [];
  const identifiers = [];
  const seenIdentifiers = new Set();
  let inFence = false;
  for (const [index, line] of lines.entries()) {
    if (/^\s*(?:```|~~~)/.test(line)) {
      inFence = !inFence;
      continue;
    }
    if (inFence) continue;
    const headingMatch = /^(#{1,6})\s+(.+?)\s*#*\s*$/.exec(line);
    if (headingMatch) {
      headings.push({
        level: headingMatch[1].length,
        line: index + 1,
        title: headingMatch[2],
      });
    }
    for (const match of line.matchAll(stableIdentifierPattern)) {
      const key = `${match[0]}:${index + 1}`;
      if (seenIdentifiers.has(key)) continue;
      seenIdentifiers.add(key);
      identifiers.push({ id: match[0], line: index + 1 });
    }
  }
  return {
    access: accessFor(path),
    category: categoryFor(absolutePath),
    charCount: content.length,
    headings,
    identifiers,
    lastReviewed: metadata["last-reviewed"] ?? null,
    lineCount: countLines(content),
    owner: metadata.owner ?? null,
    path,
    status: metadata.status ?? null,
    title:
      headings.find((heading) => heading.level === 1)?.title ?? basename(path),
  };
}

function buildIndex() {
  const excluded = new Set([repositoryPath(markdownOutputPath)]);
  const documents = collectMarkdownFiles(docsRoot)
    .filter((path) => !excluded.has(repositoryPath(path)))
    .map(parseDocument);
  return { documents, schemaVersion: 1 };
}

function markdownLink(path) {
  return encodeMarkdownPath(
    relative(dirname(markdownOutputPath), join(repositoryRoot, path)),
  );
}

function markdownTableText(value) {
  return value
    .replaceAll("\\", "\\\\")
    .replaceAll("[", "\\[")
    .replaceAll("]", "\\]")
    .replaceAll("|", "\\|");
}

function renderMarkdown(index) {
  const accessOrder = [
    "routing",
    "on-demand",
    "source",
    "historical",
    "derived",
  ];
  const labels = {
    derived: "derived",
    historical: "historical",
    "on-demand": "on-demand",
    routing: "routing",
    source: "source",
  };
  const counts = accessOrder
    .map(
      (access) =>
        `- ${labels[access]}: ${index.documents.filter((document) => document.access === access).length}`,
    )
    .join("\n");
  const rows = index.documents
    .map(
      (document) =>
        `| [${markdownTableText(document.path)}](${markdownLink(document.path)}) | ${markdownTableText(document.category)} | ${labels[document.access]} | ${markdownTableText(document.status ?? "—")} | ${markdownTableText(document.owner ?? "—")} | ${document.headings.length} | ${document.identifiers.length} |`,
    )
    .join("\n");
  return `${generatedHeader}\n\n# Document index\n\nThis file contains navigation metadata, not document bodies. Query first, then read matched sections.\n\n\`\`\`powershell\nnode scripts/document-index.mjs query task-orders\nnode scripts/document-index.mjs query ADR-001\nnode scripts/document-index.mjs watch\n\`\`\`\n\n## Access levels\n\n${counts}\n\n- Routing documents help locate facts; they are not all mandatory for every task.\n- On-demand documents expand with the actual change surface.\n- Source, historical, and derived material must not be loaded wholesale by default.\n- Full headings, line numbers, and stable IDs are in [the machine index](document-index.json).\n\n## Documents\n\n| Document | Category | Access | Status | Owner | Headings | Stable IDs |\n| --- | --- | --- | --- | --- | ---: | ---: |\n${rows}\n`;
}

function renderOutputs(index) {
  return new Map([
    [markdownOutputPath, renderMarkdown(index)],
    [jsonOutputPath, `${JSON.stringify(index, null, 2)}\n`],
  ]);
}

function writeOutputs(outputs) {
  for (const [path, content] of outputs) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
      writeFileAtomic(path, content);
    }
  }
}

function checkOutputs(outputs) {
  const failures = [];
  for (const [path, content] of outputs) {
    if (!existsSync(path))
      failures.push(`missing generated file: ${repositoryPath(path)}`);
    else if (readFileSync(path, "utf8") !== content) {
      failures.push(`stale generated file: ${repositoryPath(path)}`);
    }
  }
  return failures;
}

function execute(mode) {
  const index = buildIndex();
  const outputs = renderOutputs(index);
  if (mode === "check") {
    const failures = checkOutputs(outputs);
    if (failures.length > 0) {
      console.error("Document index check failed:");
      for (const failure of failures) console.error(`- ${failure}`);
      process.exitCode = 1;
      return;
    }
    console.log(
      `Document index is current for ${index.documents.length} Markdown files.`,
    );
    return;
  }
  writeOutputs(outputs);
  console.log(`Indexed ${index.documents.length} Markdown files.`);
}

function queryIndex(query) {
  const needle = query.toLowerCase();
  const identifierQuery = stableIdentifierExactPattern.test(query);
  const accessRank = new Map(
    ["routing", "on-demand", "source", "historical", "derived"].map(
      (access, index) => [access, index],
    ),
  );
  const matches = buildIndex()
    .documents.map((document) => {
      const headingMatches = document.headings.filter((heading) =>
        heading.title.toLowerCase().includes(needle),
      );
      const identifierMatches = document.identifiers.filter((identifier) =>
        identifier.id.toLowerCase().includes(needle),
      );
      const occupiedLines = new Set([
        ...headingMatches.map((heading) => heading.line),
        ...identifierMatches.map((identifier) => identifier.line),
      ]);
      const textMatches = readFileSync(
        join(repositoryRoot, document.path),
        "utf8",
      )
        .split(/\r?\n/)
        .map((line, index) => ({
          excerpt: line.trim().slice(0, 180),
          line: index + 1,
        }))
        .filter(
          (match) =>
            match.excerpt.toLowerCase().includes(needle) &&
            !occupiedLines.has(match.line),
        )
        .slice(0, 5);
      const metadataMatch = [
        document.access,
        document.category,
        document.owner,
        document.path,
        document.status,
        document.title,
      ].some((value) => value?.toLowerCase().includes(needle));
      if (
        !metadataMatch &&
        headingMatches.length === 0 &&
        identifierMatches.length === 0 &&
        textMatches.length === 0
      ) {
        return undefined;
      }
      return {
        access: document.access,
        headingMatches,
        identifierMatches,
        path: document.path,
        textMatches,
        title: document.title,
      };
    })
    .filter(Boolean)
    .sort(
      (left, right) =>
        (identifierQuery && /(?:DECISIONS|ADR)/i.test(left.path) ? -1 : 0) -
          (identifierQuery && /(?:DECISIONS|ADR)/i.test(right.path) ? -1 : 0) ||
        accessRank.get(left.access) - accessRank.get(right.access) ||
        compareText(left.path, right.path),
    );
  const returnedMatches = matches.slice(0, 20);
  console.log(
    JSON.stringify(
      {
        matchCount: matches.length,
        matches: returnedMatches,
        query,
        returnedCount: returnedMatches.length,
        truncated: returnedMatches.length < matches.length,
      },
      null,
      2,
    ),
  );
}

const positional = cli.positional;
const mode = positional[0] ?? "generate";
if (!["generate", "check", "query", "watch"].includes(mode)) {
  console.error(usage);
  process.exit(2);
}

if (mode === "query") {
  const query = positional.slice(1).join(" ").trim();
  if (!query) {
    console.error(
      "Document index query requires a keyword, path, heading, or stable ID.",
    );
    process.exit(2);
  }
  queryIndex(query);
} else if (mode !== "watch") {
  execute(mode);
} else {
  execute("generate");
  let timer;
  const watcher = watch(
    docsRoot,
    { recursive: true },
    (_eventType, filename) => {
      const path = normalizePath(filename ?? "");
      const markdownOutput = normalizePath(
        relative(docsRoot, markdownOutputPath),
      );
      const jsonOutput = normalizePath(relative(docsRoot, jsonOutputPath));
      if (!path || path === markdownOutput || path === jsonOutput) return;
      clearTimeout(timer);
      timer = setTimeout(() => execute("generate"), 200);
    },
  );
  console.log("Watching Markdown documents. Press Ctrl+C to stop.");
  process.on("SIGINT", () => {
    watcher.close();
    process.exit(0);
  });
}
