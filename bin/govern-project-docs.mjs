#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import console from "node:console";
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  statSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import {
  isPathWithinRoot,
  parseCliArguments,
  writeFileAtomic,
} from "../assets/runtime/docs-toolkit.mjs";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageMetadata = JSON.parse(
  readFileSync(join(packageRoot, "package.json"), "utf8"),
);
const commandName = "govern-project-docs";
const usage = `Usage: ${commandName} <command> [options]

Commands:
  init          Install the runtime, schema, and starter policies
  audit         Run a read-only repository documentation audit
  check         Run governance, generated-index, and link checks
  index         Generate, check, query, or watch the document index
  governance    Run only the Authority Engine governance check
  links         Run only the local Markdown link check

Global options:
  --help        Show help
  --version     Show the installed version

Examples:
  ${commandName} init --repo . --owner platform-team
  ${commandName} audit --repo .
  ${commandName} check --repo .
  ${commandName} index query payments --repo .`;

const installedFiles = [
  ["assets/runtime/docs-toolkit.mjs", "scripts/docs-toolkit.mjs"],
  ["assets/runtime/document-index.mjs", "scripts/document-index.mjs"],
  [
    "assets/runtime/check-doc-governance.mjs",
    "scripts/check-doc-governance.mjs",
  ],
  [
    "assets/runtime/check-markdown-links.mjs",
    "scripts/check-markdown-links.mjs",
  ],
  [
    "assets/templates/docs-governance.config.json",
    "scripts/docs-governance.config.json",
  ],
  [
    "assets/templates/docs-governance.schema.json",
    "scripts/docs-governance.schema.json",
  ],
  [
    "assets/templates/DOCUMENTATION_POLICY.md",
    "docs/governance/DOCUMENTATION_POLICY.md",
  ],
  [
    "assets/templates/AI_ENGINEERING_POLICY.md",
    "docs/governance/AI_ENGINEERING_POLICY.md",
  ],
  [
    "assets/templates/CHANGE_RECORD_TEMPLATE.md",
    "docs/archive/CHANGE_RECORD_TEMPLATE.md",
  ],
];
const generatedFiles = [
  [
    "docs/generated/document-index.md",
    (content) =>
      content.startsWith(
        "<!-- GENERATED by scripts/document-index.mjs. DO NOT EDIT. -->",
      ),
  ],
  [
    "docs/generated/document-index.json",
    (content) => {
      try {
        const index = JSON.parse(content);
        return index.schemaVersion === 2 && Array.isArray(index.documents);
      } catch {
        return false;
      }
    },
  ],
];

function runNodeScript(relativePath, argumentsList) {
  const result = spawnSync(
    process.execPath,
    [join(packageRoot, relativePath), ...argumentsList],
    { stdio: "inherit" },
  );
  if (result.error) {
    console.error(`Unable to run ${relativePath}: ${result.error.message}`);
    return 2;
  }
  return result.status ?? 2;
}

function argumentsWithDefaultRepository(argumentsList) {
  return argumentsList.includes("--repo")
    ? argumentsList
    : [...argumentsList, "--repo", process.cwd()];
}

function renderTemplate(sourcePath, owner, reviewedDate) {
  let content = readFileSync(join(packageRoot, sourcePath), "utf8");
  if (sourcePath.endsWith(".md")) {
    content = content
      .replace(/^owner: .*$/m, `owner: ${JSON.stringify(owner)}`)
      .replace(/^last-reviewed: YYYY-MM-DD$/m, `last-reviewed: ${reviewedDate}`);
  }
  return content;
}

function assertSafeInstallPath(repositoryRoot, targetPath) {
  let current = repositoryRoot;
  for (const segment of targetPath.split("/")) {
    current = join(current, segment);
    if (existsSync(current) && lstatSync(current).isSymbolicLink()) {
      throw new Error(`Install target contains a symbolic link: ${targetPath}`);
    }
  }
}

function initializeRepository(argumentsList) {
  let cli;
  try {
    cli = parseCliArguments(argumentsList, {
      booleanFlags: ["--dry-run", "--force", "--help"],
      valueFlags: ["--owner", "--repo"],
    });
    if (cli.positional.length > 0) {
      throw new Error(`Unexpected argument: ${cli.positional[0]}`);
    }
  } catch (error) {
    console.error(error.message);
    console.error(
      `Usage: ${commandName} init [--repo <path>] [--owner <name>] [--dry-run] [--force]`,
    );
    return 2;
  }
  if (cli.options["--help"]) {
    console.log(
      `Usage: ${commandName} init [--repo <path>] [--owner <name>] [--dry-run] [--force]`,
    );
    return 0;
  }

  const repositoryRoot = resolve(cli.options["--repo"] ?? process.cwd());
  const owner = cli.options["--owner"] ?? "engineering";
  const force = cli.options["--force"] ?? false;
  const dryRun = cli.options["--dry-run"] ?? false;
  if (!existsSync(repositoryRoot) || !statSync(repositoryRoot).isDirectory()) {
    console.error(`Repository does not exist: ${repositoryRoot}`);
    return 2;
  }
  if (/[\r\n]/.test(owner) || owner.trim().length === 0) {
    console.error("Owner must be a non-empty single-line value.");
    return 2;
  }

  const reviewedDate = new Date().toISOString().slice(0, 10);
  const operations = installedFiles.map(([sourcePath, targetPath]) => {
    const destination = resolve(repositoryRoot, targetPath);
    if (!isPathWithinRoot(repositoryRoot, destination)) {
      throw new Error(`Install target escapes repository root: ${targetPath}`);
    }
    assertSafeInstallPath(repositoryRoot, targetPath);
    const content = renderTemplate(sourcePath, owner.trim(), reviewedDate);
    const currentContent = existsSync(destination) && lstatSync(destination).isFile()
      ? readFileSync(destination, "utf8")
      : undefined;
    return {
      content,
      destination,
      state:
        !existsSync(destination)
          ? "create"
          : currentContent === content
            ? "unchanged"
            : "conflict",
      targetPath,
    };
  });
  const generatedConflicts = generatedFiles
    .map(([targetPath, isManaged]) => {
      const destination = resolve(repositoryRoot, targetPath);
      assertSafeInstallPath(repositoryRoot, targetPath);
      return existsSync(destination) &&
        (!lstatSync(destination).isFile() ||
          !isManaged(readFileSync(destination, "utf8")))
        ? { targetPath }
        : undefined;
    })
    .filter(Boolean);
  const conflicts = operations.filter(
    (operation) => operation.state === "conflict",
  ).concat(generatedConflicts);
  if (conflicts.length > 0 && !force) {
    console.error("Initialization stopped before writing any files.");
    console.error("Existing files differ from the packaged templates:");
    for (const conflict of conflicts) console.error(`- ${conflict.targetPath}`);
    console.error("Review them first, or rerun with --force to replace them.");
    return 1;
  }

  const planned = operations.filter(
    (operation) =>
      operation.state === "create" || force && operation.state === "conflict",
  );
  if (dryRun) {
    console.log(`Initialization plan for ${repositoryRoot}:`);
    for (const operation of planned) {
      console.log(
        `- ${operation.state === "create" ? "create" : "replace"} ${operation.targetPath}`,
      );
    }
    console.log("- generate docs/generated/document-index.{md,json}");
    console.log(`- keep ${operations.length - planned.length} unchanged file(s)`);
    return 0;
  }

  for (const operation of planned) {
    mkdirSync(dirname(operation.destination), { recursive: true });
    writeFileAtomic(operation.destination, operation.content);
  }
  console.log(
    `Installed documentation governance in ${repositoryRoot}: ${planned.length} written, ${operations.length - planned.length} unchanged.`,
  );
  return runNodeScript("assets/runtime/document-index.mjs", [
    "generate",
    "--repo",
    repositoryRoot,
  ]);
}

function checkRepository(argumentsList) {
  let cli;
  try {
    cli = parseCliArguments(argumentsList, {
      booleanFlags: ["--help"],
      valueFlags: ["--config", "--repo"],
    });
    if (cli.positional.length > 0) {
      throw new Error(`Unexpected argument: ${cli.positional[0]}`);
    }
  } catch (error) {
    console.error(error.message);
    console.error(
      `Usage: ${commandName} check [--repo <path>] [--config <path>]`,
    );
    return 2;
  }
  if (cli.options["--help"]) {
    console.log(
      `Usage: ${commandName} check [--repo <path>] [--config <path>]`,
    );
    return 0;
  }

  const repositoryRoot = resolve(cli.options["--repo"] ?? process.cwd());
  const sharedArguments = ["--repo", repositoryRoot];
  if (cli.options["--config"]) {
    sharedArguments.push("--config", resolve(cli.options["--config"]));
  }
  const checks = [
    ["assets/runtime/check-doc-governance.mjs", sharedArguments],
    ["assets/runtime/document-index.mjs", ["check", ...sharedArguments]],
    ["assets/runtime/check-markdown-links.mjs", ["--repo", repositoryRoot]],
  ];
  let exitCode = 0;
  for (const [script, scriptArguments] of checks) {
    const status = runNodeScript(script, scriptArguments);
    if (status !== 0 && exitCode === 0) exitCode = status;
  }
  return exitCode;
}

function main(argumentsList) {
  if (argumentsList.length === 0 || argumentsList[0] === "--help") {
    console.log(usage);
    return 0;
  }
  if (argumentsList[0] === "--version") {
    console.log(packageMetadata.version);
    return 0;
  }

  const [command, ...commandArguments] = argumentsList;
  if (command === "init") return initializeRepository(commandArguments);
  if (command === "check") return checkRepository(commandArguments);
  if (command === "audit") {
    return runNodeScript(
      "scripts/audit-docs.mjs",
      argumentsWithDefaultRepository(commandArguments),
    );
  }
  if (command === "index") {
    return runNodeScript(
      "assets/runtime/document-index.mjs",
      argumentsWithDefaultRepository(commandArguments),
    );
  }
  if (command === "governance") {
    return runNodeScript(
      "assets/runtime/check-doc-governance.mjs",
      argumentsWithDefaultRepository(commandArguments),
    );
  }
  if (command === "links") {
    return runNodeScript(
      "assets/runtime/check-markdown-links.mjs",
      argumentsWithDefaultRepository(commandArguments),
    );
  }

  console.error(`Unknown command: ${command}`);
  console.error(usage);
  return 2;
}

try {
  process.exitCode = main(process.argv.slice(2));
} catch (error) {
  console.error(error.message);
  process.exitCode = 2;
}
